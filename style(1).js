/* ==========================================
   RENDER PRODUCTS
========================================== */

function renderProducts(list) {

    const grid =
        document.getElementById("productsGrid");

    grid.innerHTML = "";


    if (list.length === 0) {

        grid.innerHTML = `
            <div style="
                grid-column:1/-1;
                text-align:center;
                padding:60px;
                background:white;
                border-radius:15px;
            ">

                <div style="font-size:45px">
                    🥕
                </div>

                <h3>
                    No vegetables found
                </h3>

                <p style="color:#718078">
                    Try another search.
                </p>

            </div>
        `;

        return;
    }


    list.forEach(product => {

        const card =
            document.createElement("div");

        card.className =
            "product-card";


        const stars =
            "★".repeat(
                Math.round(product.rating)
            );


        card.innerHTML = `

            <div
                class="product-image"
                style="
                    background-image:
                    url('${product.image}')
                "
            >

                <span class="product-badge">
                    Fresh
                </span>

            </div>


            <div class="product-content">

                <h3>
                    ${product.name}
                </h3>

                <div class="product-category">
                    ${getCategoryName(product.category)}
                </div>


                <div class="rating">

                    ${stars}

                    <span style="
                        color:#718078;
                        margin-left:4px;
                    ">
                        ${product.rating}
                    </span>

                </div>


                <div class="price-row">

                    <div>

                        <span class="price">
                            Rs. ${product.price}
                        </span>

                        <span class="per-kg">
                            / KG
                        </span>

                    </div>

                </div>


                <button
                    class="add-btn"
                    onclick="addToCart('${product.id}')"
                >
                    🛒 Add to Cart
                </button>

            </div>

        `;


        grid.appendChild(card);

    });

}


/* ==========================================
   CATEGORY NAME
========================================== */

function getCategoryName(category) {

    const names = {

        vegetable: "🥬 Vegetable",

        leafy: "🌿 Leafy Green",

        root: "🥕 Root Vegetable"

    };

    return names[category] || category;
}


/* ==========================================
   ADD TO CART
========================================== */

function addToCart(productId) {

    const product =
        products.find(
            p => p.id === productId
        );

    if (!product) return;


    const existing =
        cart.find(
            item => item.id === productId
        );


    if (existing) {

        existing.quantity++;

    } else {

        cart.push({

            ...product,

            quantity: 1

        });

    }


    updateCart();

    openCart();

}


/* ==========================================
   UPDATE CART
========================================== */

function updateCart() {

    const cartItems =
        document.getElementById("cartItems");

    const count =
        document.getElementById("cartCount");

    const total =
        document.getElementById("cartTotal");


    const totalItems =
        cart.reduce(
            (sum, item) =>
                sum + item.quantity,
            0
        );


    const totalPrice =
        cart.reduce(
            (sum, item) =>
                sum +
                item.price *
                item.quantity,
            0
        );


    count.textContent =
        totalItems;


    total.textContent =
        totalPrice.toLocaleString();


    if (cart.length === 0) {

        cartItems.innerHTML = `

            <div class="empty-cart">

                <div style="
                    font-size:45px;
                    margin-bottom:12px;
                ">
                    🛒
                </div>

                Your cart is empty.

                <br>

                Add some fresh vegetables!

            </div>

        `;

        return;
    }


    cartItems.innerHTML = "";


    cart.forEach(item => {

        const div =
            document.createElement("div");

        div.className =
            "cart-item";


        div.innerHTML = `

            <div
                class="cart-item-image"
                style="
                    background-image:
                    url('${item.image}')
                "
            ></div>


            <div>

                <h4>
                    ${item.name}
                </h4>

                <div class="cart-price">
                    Rs. ${item.price} / KG
                </div>


                <div class="quantity">

                    <button
                        onclick="
                        changeQuantity(
                            '${item.id}',
                            -1
                        )"
                    >
                        −
                    </button>

                    <span>
                        ${item.quantity}
                    </span>

                    <button
                        onclick="
                        changeQuantity(
                            '${item.id}',
                            1
                        )"
                    >
                        +
                    </button>

                </div>

            </div>


            <strong>
                Rs.
                ${(item.price *
                item.quantity)
                .toLocaleString()}
            </strong>

        `;


        cartItems.appendChild(div);

    });

}


/* ==========================================
   CHANGE QUANTITY
========================================== */

function changeQuantity(id, change) {

    const item =
        cart.find(
            product => product.id === id
        );

    if (!item) return;


    item.quantity += change;


    if (item.quantity <= 0) {

        cart =
            cart.filter(
                product =>
                    product.id !== id
            );

    }


    updateCart();

}


/* ==========================================
   OPEN CART
========================================== */

function openCart() {

    document
        .getElementById("cartSidebar")
        .classList.add("active");

    document
        .getElementById("overlay")
        .classList.add("active");

}


/* ==========================================
   CLOSE CART
========================================== */

function closeCart() {

    document
        .getElementById("cartSidebar")
        .classList.remove("active");

    document
        .getElementById("overlay")
        .classList.remove("active");

}


/* ==========================================
   SEARCH
========================================== */

function filterProducts() {

    const search =
        document
            .getElementById("searchInput")
            .value
            .toLowerCase()
            .trim();


    const category =
        document
            .getElementById("categoryFilter")
            .value;


    const filtered =
        products.filter(product => {

            const matchSearch =
                product.name
                    .toLowerCase()
                    .includes(search);


            const matchCategory =
                category === "all" ||
                product.category === category;


            return (
                matchSearch &&
                matchCategory
            );

        });


    renderProducts(filtered);

}


/* ==========================================
   EVENTS
========================================== */

document
    .getElementById("searchInput")
    .addEventListener(
        "input",
        filterProducts
    );


document
    .getElementById("categoryFilter")
    .addEventListener(
        "change",
        filterProducts
    );


/* ==========================================
   INITIALIZE
========================================== */

renderProducts(products);

updateCart();
